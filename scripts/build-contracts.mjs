// Solidity -> EVM bytecode -> ONE typed TypeScript module the frontend imports.
// This is the whole "build the artifact and move it to the front" step.
import solc from 'solc';
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const dir = new URL('contracts/', root);
const sources = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.sol')).map((f) => [f, { content: readFileSync(new URL(f, dir), 'utf8') }]));
const input = {
  language: 'Solidity',
  sources,
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'cancun', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'storageLayout'] } } },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) { for (const e of errors) console.error(e.formattedMessage); process.exit(1); }
for (const w of (out.errors ?? []).filter((e) => e.severity === 'warning')) console.warn(w.formattedMessage);

mkdirSync(new URL('contracts/out/', root), { recursive: true });
mkdirSync(new URL('src/generated/', root), { recursive: true });
let ts = `// Generated by scripts/build-contracts.mjs — do not edit. Rebuild with: npm run build:contracts\n\n`;
for (const [file, contracts] of Object.entries(out.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!c.evm.bytecode.object) continue; // interfaces
    const artifact = { abi: c.abi, bytecode: '0x' + c.evm.bytecode.object, deployedBytecode: '0x' + c.evm.deployedBytecode.object, storageLayout: c.storageLayout };
    writeFileSync(new URL(`contracts/out/${name}.json`, root), JSON.stringify(artifact, null, 2));
    ts += `export const ${name} = ${JSON.stringify(artifact, null, 2).replace(/^(\s*)"abi": (\[[\s\S]*?\n\1\]),/m, (m, ind, abi) => `${ind}"abi": ${abi} as const,`)} as const;\n\n`;
    console.log(`${file} -> ${name}: ${c.evm.bytecode.object.length / 2} bytes, ${c.abi.length} ABI entries`);
  }
}
writeFileSync(new URL('src/generated/contracts.ts', root), ts);
console.log('wrote src/generated/contracts.ts');
